def classify_by_keywords(problem: str) -> list[tuple[str, int]]:
    # 用关键词匹配来判断题目属于哪个分支，返回 (分支, 匹配分数) 列表
    scores = []
    problem_lower = problem.lower()

    for subject, keywords in SUBJECT_KEYWORDS.items():
        score = 0
        for kw in keywords:
            if kw.lower() in problem_lower:
                score += 1
        if score > 0:
            scores.append((subject, score))

    scores.sort(key=lambda x: x[1], reverse=True)
    return scores
